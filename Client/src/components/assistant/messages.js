export function pick(poolPath) {
  const parts = poolPath.split('.');
  let node = MESSAGE_POOL;
  for (const p of parts) {
    node = node?.[p];
    if (!node) return null;
  }
  if (!Array.isArray(node) || node.length === 0) return null;
  return node[Math.floor(Math.random() * node.length)];
}

