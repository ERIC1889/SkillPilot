export function generateChatReply(text) {
  const trimmed = (text || '').trim();
  if (!trimmed) return '뭐라고 입력해 주세요!';
  for (const rule of CHAT_RULES) {
    if (rule.match.test(trimmed)) return rule.reply();
  }
  // fallback — 짧으면 격려, 길면 정리
  if (trimmed.length < 6) {
    return '조금만 더 풀어서 말해줄래요? 어떤 부분이 막혔어요?';
  }
  return '말씀해주신 거 잘 들었어요. 일단 한 페이지만이라도 끝내고 다시 얘기해요 — 같이 가요!';
}
